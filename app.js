function applyLanguage(lang){
  const dict=translations[lang];
  document.documentElement.lang=lang;
  document.documentElement.dir=lang==="fa"?"rtl":"ltr";
  document.querySelectorAll("[data-i18n]").forEach(el=>{
    const key=el.dataset.i18n;
    if(dict[key]!==undefined) el.innerHTML=dict[key];
  });
  const btn=document.getElementById("languageToggle");
  if(btn){
    btn.querySelectorAll("span")[0].classList.toggle("lang-active",lang==="en");
    btn.querySelectorAll("span")[2].classList.toggle("lang-active",lang==="fa");
    btn.setAttribute("aria-label",lang==="en"?"Switch to Persian":"Switch to English");
  }
  document.title=lang==="en"?"Omid Hosseinpoor — AI & Data Systems Builder":"امید حسین‌پور — سازنده سیستم‌های AI و داده";
  try{localStorage.setItem("omind-lang",lang)}catch{}
}
